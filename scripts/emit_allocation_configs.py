"""Emit experiment configs from the allocator's own decisions, rather than from hand-written YAML.

H3 asks whether the joint policy beats the best single-signal policy at equal bits. If the joint arm's config
were written by hand, the comparison would test my typing rather than the allocator, and any discrepancy
between what the policy says and what the experiment runs would be invisible. So the configs are generated:
one per (budget, policy), each carrying the allocator's own rationale in its header.

    python scripts/emit_allocation_configs.py --budgets 1.05,2.0 --prefix m5h3

A policy that cannot meet a budget emits nothing and says so. That is the honest outcome for precision-only
below about 2.63 bits per original token, where quantization alone has nothing left to give up.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from raq_kv.allocation.policy import Allocation, allocate, single_signal
from raq_kv.utils.paths import configs_dir

POLICIES = ("joint", "precision_only", "retention_only", "recency_retention", "magnitude_only")


def _quant_block(plan: Allocation) -> str:
    if plan.bits is None:
        return ""
    axis = "group_token"
    return (f"quantization:\n  keys: {{bits: {plan.bits}, axis: {axis}, group_size: {plan.group_size}}}\n"
            f"  values: {{bits: {plan.bits}, axis: per_token}}\n")


def _protection_block(plan: Allocation) -> str:
    lines = []
    if plan.metadata_guard:
        lines.append(f"  metadata_guard: {plan.metadata_guard}")
    if plan.metadata_codec != "none":
        lines.append(f"  metadata_codec: {plan.metadata_codec}")
        lines.append("  metadata_word_bits: 16")
    return "protection:\n" + "\n".join(lines) + "\n" if lines else ""


def render(name: str, plan: Allocation, budget: float, policy: str, model: str) -> str:
    why = "\n".join(f"#   - {r}" for r in plan.rationale)
    return f"""# {policy} at a budget of {budget:.4f} bits per ORIGINAL token.
#
# GENERATED by scripts/emit_allocation_configs.py from the allocator's own decision. Hand-editing it would
# break the thing H3 is testing: that what the policy decides is what the experiment runs.
#
# The allocator's reasoning for this configuration:
{why}
#
# Spends {plan.bits_per_original_token:.4f} of the {budget:.4f} available.
include:
  - models/{model}.yaml
  - datasets/raq_probe_v0.yaml
name: {name}
{_quant_block(plan)}{_protection_block(plan)}compression:
  scorer: {plan.scorer}
  ratio: {plan.retention_ratio}
  unit: {plan.unit}
  protect_initial: {plan.protect_initial}
task:
  kind: retention
  n_samples: 120
seed: 0
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--budgets", default="1.05,2.0", help="Comma-separated bits per original token")
    parser.add_argument("--ber", type=float, default=1e-6)
    parser.add_argument("--prefix", default="m5h3")
    # The cross-family replicate H3 pre-registers (docs/m4_m5_plan.md §M5). Llama-3.2-3B has the same KV
    # geometry as Qwen3-1.7B -- verified, both 57344 values per token -- so the allocator's cost table transfers
    # unchanged and only the family varies. The eager variant is picked automatically for attention scorers.
    parser.add_argument("--model", default="qwen3_1p7b",
                        help="Base model config stem; '_eager' is appended for scorers that read attention")
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args()

    out = args.out or (configs_dir() / "experiments")
    written, skipped = [], []
    for budget in (float(b) for b in args.budgets.split(",")):
        tag = f"{budget:.2f}".replace(".", "p")
        for policy in POLICIES:
            plan = allocate(budget, args.ber) if policy == "joint" else single_signal(policy, budget, args.ber)
            if plan is None:
                skipped.append(f"{policy} at {budget}: infeasible - this policy cannot reach that budget")
                continue
            # A scorer that needs attention weights needs eager attention (D5), which is its own model config.
            needs_eager = plan.scorer in ("query_attention", "window_attention")
            model = f"{args.model}_eager" if needs_eager else args.model
            name = f"{args.prefix}_{tag}_{policy}"
            (out / f"{name}.yaml").write_text(render(name, plan, budget, policy, model), encoding="utf-8")
            written.append(f"{name}: ratio {plan.retention_ratio}, bits {plan.bits}, group {plan.group_size}, "
                           f"spends {plan.bits_per_original_token:.4f}")
    print("\n".join(written) if written else "nothing written")
    if skipped:
        print("\nnot emitted:")
        print("\n".join(f"  {s}" for s in skipped))
    return 0


if __name__ == "__main__":
    sys.exit(main())
